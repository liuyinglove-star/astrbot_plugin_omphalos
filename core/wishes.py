def select_wishes(
    context_tags: set[str] | None = None,
    rng: random.Random | None = None,
) -> list[Wish]:
    """按本轮经历抽取十二位黄金裔的祝福。

    Args:
        context_tags: 本局出现过的情节标记。
        rng: 随机源；传固定种子可复现。

    Returns:
        list[Wish]: 12 条祝福，最后一条是昔涟。
    """
    rng = rng or random.Random()
    tags = context_tags or set()
    chosen: list[Wish] = []

    for pool in POOLS.values():
        weights = [
            w.weight * (2.2 if (w.tags and tags & set(w.tags)) else 1.0)
            for w in pool
        ]
        chosen.append(rng.choices(pool, weights=weights, k=1)[0])

    cw = [
        w.weight * (2.0 if (w.tags and tags & set(w.tags)) else 1.0)
        for w in CYRENE_POOL
    ]
    chosen.append(rng.choices(CYRENE_POOL, weights=cw, k=1)[0])
    return chosen


def pick_voice_line(rng: random.Random | None = None) -> str:
    """随机挑一句昔涟的语音短句。

    Args:
        rng: 随机源。

    Returns:
        str: 可念的短句。
    """
    rng = rng or random.Random()
    return rng.choice(CYRENE_VOICE_LINES)


def all_wishes() -> list[Wish]:
    """返回每个角色的第一条，供调试预览。

    Returns:
        list[Wish]: 13 条（含昔涟）。
    """
    out = [pool[0] for pool in POOLS.values()]
    out.append(CYRENE_POOL[0])
    return out
